import { chromium } from 'playwright';
const b = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await b.newContext({ viewport: { width: 1512, height: 950 }, deviceScaleFactor: 2 });
const p = await ctx.newPage();
await p.goto('http://127.0.0.1:8787', { waitUntil: 'domcontentloaded', timeout: 30000 }).catch(e=>console.log('goto:', e.message));
await p.waitForTimeout(7000);
console.log('URL=' + p.url());
console.log('TITLE=' + await p.title());
console.log('BODY=' + (await p.innerText('body').catch(()=>'')).slice(0,400).replace(/\s+/g,' '));
await p.screenshot({ path: 'D:/tmp/wb1.png' });
await b.close();
