test('late cancellation errors and unrelated storage changes keep a mobile call alive', { timeout: 90000 }, async t => {
  const f = await setup(t)
  await f.panel.getByRole('button', { name: '开始通话', exact: true }).click()
  await f.panel.getByText('已连接，可以说话', { exact: true }).waitFor()
  await f.panel.getByRole('button', { name: '转写', exact: true }).click()
  await f.panel.getByText('帮我生成一份通话任务测试报告', { exact: true }).waitFor()
  const p = f.providers[0]
  p.event({ type: 'response.created', response: { id: 'interrupt-race' } })
  p.event({ type: 'input_audio_buffer.speech_started' })
  p.event({ type: 'input_audio_buffer.speech_started' })
  for (let i = 0; i < 100 && !p.sent.some(e => e.type === 'response.cancel'); i++) await new Promise(r => setTimeout(r, 50))
  const cancels = p.sent.filter(e => e.type === 'response.cancel')
  assert.equal(cancels.length, 1)
  p.event({ type: 'response.done', response: { id: 'interrupt-race' } })
  p.event({ type: 'error', error: { type: 'invalid_request_error', event_id: cancels[0].event_id, message: 'no ongoing response to cancel' } })
  await f.page.evaluate(() => window.dispatchEvent(new StorageEvent('storage', { key: 'theme', newValue: 'dark' })))
  p.event({ type: 'response.created', response: { id: 'after-recovery' } })
  p.event({ type: 'response.audio.delta', response_id: 'after-recovery', item_id: 'recovered-audio', delta: Buffer.alloc(4800).toString('base64') })
  p.event({ type: 'response.audio_transcript.delta', response_id: 'after-recovery', delta: '打断后仍可继续通话' })
  p.event({ type: 'response.done', response: { id: 'after-recovery' } })
  await f.panel.getByText('打断后仍可继续通话', { exact: true }).waitFor()
  await f.panel.getByRole('button', { name: '回到动态画面', exact: true }).click()
  await f.panel.getByRole('button', { name: '静音', exact: true }).click()
  await f.panel.getByRole('button', { name: '取消静音', exact: true }).click()
  assert.equal(p.dead, undefined)
  assert.equal(f.providers.length, 1)
  p.event({ type: 'error', error: { type: 'invalid_request_error', event_id: 'unrelated', message: 'no ongoing response to cancel' } })
  await f.panel.getByText('语音服务未能处理本次请求。请重新开始；若再次中断，请反馈发生时的操作。', { exact: true }).waitFor()
  await f.page.setViewportSize({ width: 390, height: 460 })
  const retry = f.panel.getByRole('button', { name: '再次通话', exact: true })
  await reachable(f.page, retry)
  await reachable(f.page, f.panel.getByRole('button', { name: '返回聊天', exact: true }))
  const directory = new URL('../../.impeccable/review/', import.meta.url); await fs.mkdir(directory, { recursive: true })
  await f.page.screenshot({ path: fileURLToPath(new URL('mobile-call-error.png', directory)), fullPage: true })
  await retry.click()
  await f.panel.getByText('已连接，可以说话', { exact: true }).waitFor()
  assert.equal(f.providers.length, 2)
  await f.panel.getByRole('button', { name: '挂断', exact: true }).click()
  assert.deepEqual(f.errors, [])
})

