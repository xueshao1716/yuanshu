const { chromium } = await import(process.env.YUANSHU_PLAYWRIGHT_MODULE || 'playwright')

async function setup(t, { empty = false, width = 390, microphone = 'granted' } = {}) {
  const f = await startChatVoiceFixture(t, { shell: true })
  const browser = await chromium.launch({ headless: true, args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] })
  t.after(() => browser.close())
  const context = await browser.newContext({ viewport: { width, height: 844 }, hasTouch: width < 900, permissions: ['microphone'] })
  const page = await context.newPage(), errors = []; page.setDefaultTimeout(15000)
  page.on('pageerror', e => errors.push(e.message))
  let created = !empty, creates = 0
  await context.route('**/*', route => {
    const u = new URL(route.request().url()), json = value => route.fulfill({ json: value })
    if (u.origin !== f.origin) return route.abort()
    if (u.pathname.startsWith('/api/voice/')) return route.continue()
    if (u.pathname === '/api/sessions') {
      if (route.request().method() === 'POST') { created = true; creates++; return json({ id: creates === 1 ? f.id : 'fixture-next', name: '通话测试' }) }
      return json({ sessions: created ? [{ id: f.id, name: '通话测试', updatedAt: new Date().toISOString() }] : [] })
    }
    if (u.pathname===`/api/sessions/${f.id}/messages` || u.pathname===`/api/sessions/${f.id}/stream`) return route.continue()
    if (u.pathname.endsWith('/messages')) return json({ messages: [], truncated: false })
    if (u.pathname.endsWith('/stream')) return route.fulfill({ contentType: 'text/event-stream', body: 'event: subscribed\ndata: {"lastSeq":0}\n\n' })
    if (u.pathname === '/api/run/overview') return json({ active: [], recent: [] })
    if (u.pathname.startsWith('/api/')) return json({})
    return route.continue()
  })
  await page.addInitScript(({ id, empty }) => {
    localStorage.setItem('yuanshu_access_token', 'fixture-only')
    if (!empty) localStorage.setItem('pi_last_session', id)
  }, { id: f.id, empty })
  if (microphone !== 'granted') await page.addInitScript(mode => {
    navigator.mediaDevices.getUserMedia = () => mode === 'denied'
      ? Promise.reject(new DOMException('Permission denied', 'NotAllowedError')) : new Promise(() => {})
  }, microphone)
  await page.goto(f.origin + '/__voice#/chat', { waitUntil: 'domcontentloaded' })
  await page.waitForFunction(() => { const el = document.querySelector('.flex'); return el && getComputedStyle(el).display === 'flex' })
  const panel = page.getByRole('region', { name: '实时通话', exact: true })
  const draft = page.locator('.mobile-composer textarea').first()
  await draft.fill('通话前的草稿，请保留')
  await page.getByRole('button', { name: '语音通话', exact: true }).click()
  await panel.getByRole('checkbox').check()
  return { ...f, page, panel, errors, creates: () => creates }
}

async function reachable(page, locator) {
  await locator.scrollIntoViewIfNeeded()
  const box = await locator.boundingBox(), viewport = page.viewportSize()
  assert.ok(box && box.y >= 0 && box.y + box.height <= viewport.height && box.x >= 0 && box.x + box.width <= viewport.width, 'control is inside the actual viewport: ' + JSON.stringify(box))
  const hit = await locator.evaluate(el => {
    const r = el.getBoundingClientRect()
    const at = document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)
    return { reachable: el.contains(at), at: at?.outerHTML.slice(0, 240), target: el.textContent }
  })
  assert.ok(hit.reachable, 'control is not clipped or covered: ' + JSON.stringify(hit))
}

test('new-chat creation preserves mounted call and real chat switches stop it', { timeout: 90000 }, async t => {
  const f = await setup(t, { empty: true, width: 1440 })
  await f.panel.getByRole('button', { name: '开始通话', exact: true }).click()
  await f.panel.getByText('已连接，可以说话', { exact: true }).waitFor()
  assert.equal(f.creates(), 1)
  assert.equal(f.providers.length, 1)
  assert.equal(f.providers[0].dead, undefined)
  await f.panel.getByRole('button', { name: '结束并返回聊天', exact: true }).click()
  await f.page.waitForFunction(() => !document.querySelector('.voice-screen'))
  assert.equal(await f.page.locator('.mobile-composer textarea').first().inputValue(), '通话前的草稿，请保留')
  await f.page.getByRole('button', { name: '新建会话', exact: true }).click()
  assert.deepEqual(f.errors, [])
})

test('accepted task returns through real session stream into original chat after hangup and refresh', { timeout: 90000 }, async t => {
  const f = await setup(t)
  await f.panel.getByRole('button', { name: '开始通话', exact: true }).click()
  await f.panel.getByText('已连接，可以说话', { exact: true }).waitFor()
  f.providers[0].event({ type: 'response.function_call_arguments.done', call_id: 'return-to-chat', name: 'propose_tasks',
    arguments: JSON.stringify({ tasks: [{ title: '原聊天结果测试', instruction: '只在隔离测试目录生成一份便条' }] }) })
  await f.panel.getByRole('button', { name: /项任务等待你确认/ }).click()
  await f.panel.getByRole('button', { name: '确认执行', exact: true }).waitFor()
  assert.equal(f.executions.length, 0)
  await f.panel.getByRole('button', { name: '确认执行', exact: true }).click()
  await f.panel.getByText('已受理，挂断后任务继续，结果会回到当前聊天。', { exact: true }).waitFor()
  await f.panel.getByRole('button', { name: '挂断', exact: true }).click()
  await f.panel.getByRole('button', { name: '返回聊天', exact: true }).click()
  for (let i=0; i<100 && !f.executions.length; i++) await new Promise(r=>setTimeout(r,50))
  assert.equal(f.executions.length, 1)
  const [task] = await f.runtime.list(f.id)
  await f.finish(task); await f.runtime.tick()
  await f.page.getByText('隔离执行器已生成结果。', { exact: true }).waitFor()
  assert.equal(f.rows().filter(r => r.message?.voiceDeliveryId).length, 1)
  assert.equal(await f.page.evaluate(() => localStorage.getItem('pi_last_session')), f.id)
  await f.page.reload({ waitUntil: 'domcontentloaded' })
  await f.page.getByText('隔离执行器已生成结果。', { exact: true }).waitFor()
  assert.equal(f.executions.length, 1)
  assert.deepEqual(f.errors, [])
})

