import assert from 'node:assert/strict'
import test from 'node:test'
import fs from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { startChatVoiceFixture } from './fixtures/chat-voice-server.mjs'
const {chromium}=await import(process.env.YUANSHU_PLAYWRIGHT_MODULE||'playwright')
const until=async fn=>{for(let i=0;i<100;i++){if(await fn())return;await new Promise(r=>setTimeout(r,50))}throw Error('condition timeout')}

for(const width of [1440,390]) test('voice handoff persists after hangup and refresh at '+width+'px',{timeout:90000},async t=>{
  const f=await startChatVoiceFixture(t)
  const browser=await chromium.launch({headless:true,args:['--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream']})
  t.after(()=>browser.close())
  const context=await browser.newContext({viewport:{width,height:960},hasTouch:width<900,permissions:['microphone']})
  const page=await context.newPage(), errors=[], external=[];page.setDefaultTimeout(12000)
  page.on('pageerror',e=>errors.push(e.message))
  await context.route('**/*',route=>{if(new URL(route.request().url()).origin!==f.origin){external.push(route.request().url());return route.abort()}return route.continue()})
  await page.addInitScript(()=>localStorage.setItem('yuanshu_access_token','fixture-only'))
  await page.goto(f.origin+'/__voice',{waitUntil:'domcontentloaded'})
  await page.getByRole('button',{name:'语音通话',exact:true}).click()
  await page.getByRole('checkbox').check()
  await page.getByRole('button',{name:'开始通话',exact:true}).click()
  await page.getByText('已连接，可以说话',{exact:true}).waitFor()
  await page.getByRole('button',{name:'转写',exact:true}).click()
  await page.getByRole('button',{name:'交给元枢',exact:true}).click()
  const input=page.getByRole('textbox',{name:'任务内容（可修改转写）'})
  assert.equal(await input.inputValue(),'帮我生成一份通话任务测试报告')
  await input.fill('只在隔离目录生成一份通话交接便条')
  await page.getByRole('button',{name:'生成任务确认',exact:true}).click()
  await page.getByRole('button',{name:'确认执行',exact:true}).waitFor()
  assert.equal(f.executions.length,0)
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no horizontal overflow')
  const bounds=await page.getByRole('button',{name:'确认执行',exact:true}).boundingBox();assert.ok(bounds.height>=44)
  const directory=new URL('../../.impeccable/review/component/',import.meta.url);await fs.mkdir(directory,{recursive:true})
  await page.evaluate(()=>scrollTo(0,0))
  await page.screenshot({path:fileURLToPath(new URL(width===390?'mobile.png':'desktop.png',directory)),fullPage:true})
  await page.getByRole('button',{name:'确认执行',exact:true}).click()
  await page.getByText('已受理，挂断后任务继续，结果会回到当前聊天。',{exact:true}).waitFor()
  await until(()=>f.executions.length===1)
  await page.getByRole('button',{name:'挂断',exact:true}).click()
  await page.getByRole('button',{name:'返回聊天',exact:true}).click()
  assert.ok(f.providers[0].audioBytes>0,'real browser capture reaches WebSocket')
  const [task]=await f.runtime.list(f.id)
  await f.finish(task);await f.runtime.tick()
  await page.getByRole('region',{name:'原聊天回执'}).getByText('隔离执行器已生成结果。',{exact:false}).waitFor()
  assert.equal(f.rows().filter(r=>r.message?.voiceDeliveryId).length,1)
  await page.reload({waitUntil:'domcontentloaded'})
  await page.getByRole('button',{name:'语音通话',exact:true}).click()
  await page.getByRole('button',{name:'任务',exact:true}).click()
  await page.getByRole('list',{name:'已受理任务'}).getByText('执行结束 · 结果已回到聊天',{exact:true}).waitFor()
  assert.equal(f.executions.length,1)
  await page.getByRole('button',{name:'通话',exact:true}).click()
  await page.getByRole('checkbox').check();await page.getByRole('button',{name:'开始通话',exact:true}).click()
  await page.getByText('已连接，可以说话',{exact:true}).waitFor()
  const provider=f.providers.at(-1)
  provider.event({type:'response.function_call_arguments.done',call_id:'decline1',name:'propose_tasks',arguments:JSON.stringify({tasks:[{title:'不要执行',instruction:'拒绝测试'}]})})
  await page.getByRole('button',{name:/^任务/}).click()
  await page.getByRole('button',{name:'不执行',exact:true}).click()
  await page.getByText('已取消，不执行',{exact:true}).waitFor()
  assert.equal((await f.runtime.list(f.id)).length,1)
  await input.fill('测试停止任务');await page.getByRole('button',{name:'生成任务确认',exact:true}).click()
  await page.getByRole('button',{name:'确认执行',exact:true}).click()
  await until(()=>f.executions.length===2)
  await page.getByRole('button',{name:'停止任务',exact:true}).click()
  await until(async()=> (await f.runtime.list(f.id))[1].status==='stopped')
  await page.getByRole('button',{name:'挂断',exact:true}).click()
  assert.deepEqual(errors,[]);assert.deepEqual(external,[])
})
