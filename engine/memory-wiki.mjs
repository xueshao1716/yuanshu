// ===== memory-wiki.mjs —— 把记忆与知识渲染成「人能读」的主题页（2026-10-27）=====
//
// 抄 A5 的 Workspace Wiki / EverOS 的 Knowledge Wiki：
//   · **面向人**（不是给模型塞上下文），按主题聚合、互相链接；
//   · 每页标注**来源**（哪个文件/哪条知识），可溯源；
//   · 再生是幂等的，但**不覆盖人改过的页**（带 `<!-- generated -->` 标记的才重写）。
//
// 不调模型：全部是规则聚合（我们的知识库已有 claim，记忆/经验库都有小标题）。
import fs from "node:fs";
import path from "node:path";

export const WIKI_DIR = path.join("记忆", "Wiki");
export const MARKER = "<!-- generated by memory-wiki; 手写的页面不会被覆盖 -->";
export const MAX_PAGE_CHARS = 14000;
export const MAX_ITEMS_PER_TOPIC = 40;

const dirOf = (wsRoot) => path.join(String(wsRoot || "."), WIKI_DIR);
const fileOf = (wsRoot, name) => path.join(dirOf(wsRoot), `${name}.md`);

/**
 * 主题名：截到第一个分隔符（"当前状态（2026-08-23）·React" → "当前状态"），
 * 再把路径非法字符换掉。太长会把列表撑爆、也不好找。
 */
const slug = (s) => String(s || "")
  .trim()
  .split(/[（(·|｜:：]/)[0]
  .replace(/[\\/*?"<>|\s]+/g, "-")
  .replace(/-+/g, "-")
  .replace(/^-|-$/g, "")
  .slice(0, 24) || "未命名";

function readIfExists(p) {
  try { return fs.readFileSync(p, "utf8") } catch { return "" }
}

/** 从 `## 标题` 分节（记忆.md / experience.md 共用）。 */
export function sectionsOf(text, { maxItems = MAX_ITEMS_PER_TOPIC } = {}) {
  const out = [];
  const parts = String(text || "").split(/^## /m).slice(1);
  for (const part of parts) {
    const nl = part.indexOf("\n");
    const title = (nl >= 0 ? part.slice(0, nl) : part).trim();
    const body = (nl >= 0 ? part.slice(nl + 1) : "").trim();
    if (!title || !body) continue;
    out.push({ title, body: body.slice(0, MAX_PAGE_CHARS / 2), lines: body.split(/\r?\n/).filter((l) => l.trim()).slice(0, maxItems) });
  }
  return out;
}

/** 知识条目 → 按 claim 类型聚合成主题。 */
export function topicsFromKnowledge(wsRoot, { now = Date.now(), maxItems = MAX_ITEMS_PER_TOPIC } = {}) {
  const dir = path.join(String(wsRoot || "."), "记忆", "知识", "entries");
  let files = [];
  try { files = fs.readdirSync(dir).filter((f) => f.endsWith(".json")) } catch { return [] }
  const buckets = new Map();   // type -> Map(claimKey -> {value, count, ids})
  for (const f of files) {
    let e;
    try { e = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")) } catch { continue }
    if (e.expiresAt && Number(e.expiresAt) < now) continue;
    for (const c of e.claims || []) {
      const type = c.type || "fact";
      const byKey = buckets.get(type) || new Map();
      const prev = byKey.get(c.key) || { value: c.value, count: 0, ids: [] };
      prev.count += 1;
      if (prev.ids.length < 3) prev.ids.push(String(e.id || "").slice(0, 10));
      byKey.set(c.key, prev);
      buckets.set(type, byKey);
    }
  }
  const label = { decision: "决定", preference: "偏好", lesson: "教训", fact: "事实" };
  const out = [];
  for (const [type, byKey] of buckets) {
    const items = [...byKey.values()].sort((a, b) => b.count - a.count).slice(0, maxItems);
    if (!items.length) continue;
    out.push({
      title: `${label[type] || type}`,
      kind: "knowledge",
      items: items.map((i) => ({ text: i.value, meta: `${i.count} 次 · ${i.ids.join(",")}` })),
    });
  }
  return out;
}

/** 生成一页 Markdown。 */
function renderPage({ title, kind, intro, items, sources, related = [] }) {
  const lines = [
    MARKER,
    `# ${title}`,
    "",
    `> ${intro || "由记忆与知识库自动聚合。"}`,
    "",
    `- 类型：${kind}`,
    `- 生成时间：${new Date().toISOString().slice(0, 16)}`,
    `- 来源：${(sources || []).join("、") || "（自动聚合）"}`,
    "",
    ...(items || []).map((i) => (typeof i === "string" ? `- ${i}` : `- ${i.text}${i.meta ? `\n  - <sub>${i.meta}</sub>` : ""}`)),
    "",
  ];
  if (related.length) {
    lines.push("## 相关", "", ...related.map((r) => `- [[${r}]]`), "");
  }
  let text = lines.join("\n");
  if (text.length > MAX_PAGE_CHARS) {
    text = text.slice(0, MAX_PAGE_CHARS) + `\n\n> （超长已截断，完整内容见源文件）\n`;
  }
  return text;
}

/**
 * 生成/更新 Wiki。
 * @returns {{ok:boolean, written:string[], kept:string[], topics:number, indexPath:string}}
 */
export function buildWiki({ wsRoot, now = Date.now() } = {}) {
  const ws = String(wsRoot || ".");
  const dir = dirOf(ws);
  fs.mkdirSync(dir, { recursive: true });

  const written = [];
  const kept = [];

  const write = (name, content) => {
    const p = fileOf(ws, name);
    const existing = readIfExists(p);
    if (existing && !existing.startsWith(MARKER)) { kept.push(name); return false }  // 人改过 → 不动
    fs.writeFileSync(p, content, "utf8");
    written.push(name);
    return true;
  };

  // ① 记忆.md 的分节 → 每节一页
  const memory = readIfExists(path.join(ws, "记忆.md"));
  for (const s of sectionsOf(memory)) {
    if (s.lines.join("").length < 1) continue;   // 空壳节不建页
    write(slug(s.title), renderPage({
      title: s.title, kind: "固定记忆", intro: "来自 `记忆.md`（固定记忆，跨会话长期有效）。",
      items: s.lines, sources: ["记忆.md"],
    }));
  }

  // ② 经验库 → 「经验」总页（按小标题聚合）
  const exp = readIfExists(path.join(ws, "工程", "经验库", "experience.md"));
  const expSections = sectionsOf(exp, { maxItems: 6 });
  if (expSections.length) {
    write("经验库", renderPage({
      title: "经验库", kind: "经验", intro: "来自 `工程/经验库/experience.md`（做法沉淀，可增长）。",
      items: expSections.map((s) => ({ text: `**${s.title}**\n${s.lines.slice(0, 2).join("\n")}` })),
      sources: ["工程/经验库/experience.md"],
      related: expSections.slice(0, 8).map((s) => slug(s.title)),
    }));
  }

  // ③ 知识库 claim → 决定/偏好/教训/事实
  const kTopics = topicsFromKnowledge(ws, { now });
  for (const t of kTopics) {
    write(slug(t.title), renderPage({
      title: t.title, kind: "知识", intro: "来自知识库的 claim（同 key 已合并，括号里是出现次数与来源条目）。",
      items: t.items, sources: ["记忆/知识/entries"],
      related: kTopics.map((x) => slug(x.title)).filter((x) => x !== slug(t.title)).slice(0, 4),
    }));
  }

  // ④ 索引
  const topics = [...new Set([...written, ...kept])];
  const index = [
    MARKER,
    "# 记忆 Wiki",
    "",
    "> 这一页是**给人看的**：把散在记忆、经验库、知识库里的东西按主题摊开。",
    "> 带自动标记的页会被重写；你把标记删掉，我就再也不动它。",
    "",
    `- 更新时间：${new Date(now).toISOString().slice(0, 16)}`,
    `- 主题数：${topics.length}`,
    "",
    "## 主题",
    "",
    ...topics.sort().map((t) => `- [[${t}]]`),
    "",
  ].join("\n");
  const indexPath = path.join(dir, "index.md");
  fs.writeFileSync(indexPath, index, "utf8");

  return { ok: true, written, kept, topics: topics.length, indexPath };
}

export function listWiki({ wsRoot } = {}) {
  const dir = dirOf(wsRoot);
  try {
    return fs.readdirSync(dir).filter((f) => f.endsWith(".md")).map((f) => {
      const st = fs.statSync(path.join(dir, f));
      return { name: f.replace(/\.md$/, ""), bytes: st.size, updatedAt: st.mtimeMs };
    }).sort((a, b) => a.name.localeCompare(b.name));
  } catch { return [] }
}

export function readWiki({ wsRoot, topic } = {}) {
  const name = String(topic || "").replace(/\.md$/, "");
  if (!/^[\w\u4e00-\u9fa5][\w\u4e00-\u9fa5\-. ]{0,60}$/.test(name)) return { ok: false, error: "主题名不合法" };
  const p = fileOf(wsRoot, name);
  try { return { ok: true, topic: name, content: fs.readFileSync(p, "utf8") } }
  catch { return { ok: false, error: "没有这个主题" } }
}
