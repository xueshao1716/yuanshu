// ===== wiki-stale.mjs —— 源文档变了，标出"待复核"的 Wiki 页（2026-10-27）=====
//
// 把 Diff Engine 和 Wiki 串起来：
//   · 自动生成的页，源变了 → 下次重建会刷新，不需要人管；
//   · **手写页**（人删掉了自动标记）源变了 → 没人会去更新，这才是要提醒的。
//
// 做法：`记忆/Wiki/.stale.json` 记「页 → 何时、因为哪个文件」。页面顶部加一行醒目提示，
// 索引里单列一节；重建能刷新的页自动清标记，手写页的标记留着等人处理。
import fs from "node:fs";
import path from "node:path";

export const WIKI_DIR = path.join("记忆", "Wiki");
export const STALE_FILE = ".stale.json";
export const MARKER = "<!-- generated by memory-wiki; 手写的页面不会被覆盖 -->";

const dirOf = (ws) => path.join(String(ws || "."), WIKI_DIR);

export function readStale(wsRoot) {
  try {
    const raw = JSON.parse(fs.readFileSync(path.join(dirOf(wsRoot), STALE_FILE), "utf8"));
    if (raw && typeof raw === "object" && raw.pages) return raw;
  } catch {}
  return { v: 1, pages: {} };
}

export function writeStale(wsRoot, data) {
  const dir = dirOf(wsRoot);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, STALE_FILE), JSON.stringify({ ...data, v: 1, updatedAt: Date.now() }, null, 2), "utf8");
  return data;
}

/** 页面声明了哪些来源（读 `- 来源：a、b` 那行）。 */
export function sourcesOfPage(text) {
  const m = String(text || "").match(/^- 来源：(.+)$/m);
  if (!m) return [];
  return m[1].split(/[、,，]/).map((x) => x.trim()).filter(Boolean);
}

function pathMatches(source, changedPath) {
  const s = source.replace(/\\/g, "/").toLowerCase();
  const c = String(changedPath || "").replace(/\\/g, "/").toLowerCase();
  if (!s || !c) return false;
  if (c === s || c.startsWith(s.replace(/\/$/, "") + "/")) return true;
  const base = s.split("/").pop();
  return !!base && base.length >= 4 && c.split("/").pop() === base;
}

/**
 * 标脏：给定变化的文档路径，找出"来源里包含它们"的 Wiki 页。
 * @returns {{marked:string[], already:number}}
 */
export function markStaleForPaths({ wsRoot, paths = [], now = Date.now() } = {}) {
  const dir = dirOf(wsRoot);
  let files = [];
  try { files = fs.readdirSync(dir).filter((f) => f.endsWith(".md") && f !== "index.md") } catch { return { marked: [], already: 0 } }
  const stale = readStale(wsRoot);
  const marked = [];
  let already = 0;

  for (const f of files) {
    const topic = f.replace(/\.md$/, "");
    let text = "";
    try { text = fs.readFileSync(path.join(dir, f), "utf8") } catch { continue }
    const declared = sourcesOfPage(text).filter((src) => paths.some((p) => pathMatches(src, p)));
    // 兜底：手写页常常没有「来源」行——那就拿主题名去和变更路径比（文件名包含主题名即算）
    const byName = declared.length
      ? []
      : paths.filter((p2) => String(p2).toLowerCase().includes(String(topic).toLowerCase()));
    const hit = declared.length ? declared : byName;
    if (!hit.length) continue;
    if (stale.pages[topic]) { already += 1; continue }
    stale.pages[topic] = { at: now, because: hit.slice(0, 3), generated: text.startsWith(MARKER) };
    marked.push(topic);
  }
  if (marked.length) writeStale(wsRoot, stale);
  return { marked, already };
}

/** 重建后清掉"自动页"的标记（手写页的留着）。 */
export function clearStaleForGenerated({ wsRoot, topics = [] } = {}) {
  const stale = readStale(wsRoot);
  let cleared = 0;
  for (const t of topics) {
    if (stale.pages[t]?.generated) { delete stale.pages[t]; cleared += 1 }
  }
  if (cleared) writeStale(wsRoot, stale);
  return { cleared, left: Object.keys(stale.pages).length };
}

export function staleSummary(wsRoot) {
  const stale = readStale(wsRoot);
  const pages = Object.entries(stale.pages).map(([topic, info]) => ({ topic, ...info }));
  return { count: pages.length, pages: pages.sort((a, b) => (b.at || 0) - (a.at || 0)) };
}

/** 环境事实一行。 */
export function staleWikiLine(wsRoot, { maxItems = 3 } = {}) {
  // 只提醒**手写页**：自动页下次重建会刷新，不值得占一行上下文
  const { pages } = staleSummary(wsRoot);
  const hand = pages.filter((p) => !p.generated);
  if (!hand.length) return "";
  const names = hand.slice(0, maxItems).map((p) => p.topic).join("、");
  return `【Wiki 待复核】${hand.length} 个手写页的来源文档改过：${names}——自动页会自己刷新，这些要你看一眼。`;
}
